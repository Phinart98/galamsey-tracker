"""Append a STAC Item per detection period to a static catalog.json on R2.

This is a deliberately small footprint: one Catalog file listing Items by
relative href, one Item per month. No pgstac, no stac-fastapi -- a researcher
just points pystac_client at the catalog URL.

The 'forkuor:' extension keys document the detection parameters used so
later runs with different thresholds are self-describing.
"""

import json
import os
from datetime import UTC, date, datetime
from typing import Any

import boto3
import structlog
from botocore.config import Config
from botocore.exceptions import ClientError

log = structlog.get_logger()

CATALOG_KEY = "cog/sentinel1/catalog.json"
ITEM_KEY_TEMPLATE = "cog/sentinel1/items/{period}.json"
COG_KEY_TEMPLATE = "cog/sentinel1/{period}.tif"

GHANA_BBOX = [-3.26, 4.74, 1.20, 11.18]


def _client() -> Any:
    """Boto3 S3 client bound to Cloudflare R2.

    Path-style addressing is required (see cog.upload_to_r2 for the why).
    """
    account_id = os.environ["R2_ACCOUNT_ID"]
    return boto3.client(
        "s3",
        endpoint_url=(
            os.environ.get("R2_ENDPOINT_URL")
            or f"https://{account_id}.r2.cloudflarestorage.com"
        ),
        aws_access_key_id=os.environ["R2_ACCESS_KEY_ID"],
        aws_secret_access_key=os.environ["R2_SECRET_ACCESS_KEY"],
        region_name="auto",
        config=Config(s3={"addressing_style": "path"}),
    )


def _public_url(key: str) -> str:
    account_id = os.environ["R2_ACCOUNT_ID"]
    bucket = os.environ.get("R2_BUCKET", "galamsey-static")
    base = os.environ.get(
        "R2_PUBLIC_BASE_URL", f"https://{bucket}.{account_id}.r2.dev"
    ).rstrip("/")
    return f"{base}/{key}"


def _empty_catalog() -> dict[str, Any]:
    return {
        "type": "Catalog",
        "id": "galamsey-tracker-sentinel1-change",
        "stac_version": "1.0.0",
        "description": (
            "Monthly Sentinel-1 SAR backscatter-delta change detections over "
            "Ghana, after Forkuor et al. 2020. Generated by the Galamsey "
            "Tracker open-source pipeline at github.com/Phinart98/galamsey-tracker."
        ),
        "links": [
            {"rel": "self", "href": _public_url(CATALOG_KEY), "type": "application/json"},
            {"rel": "root", "href": _public_url(CATALOG_KEY), "type": "application/json"},
        ],
        "stac_extensions": [],
    }


def _build_item(
    period: str,
    period_start: date,
    period_end: date,
    threshold_db: float,
    baseline_months: int,
    cog_url: str,
) -> dict[str, Any]:
    now = datetime.now(tz=UTC).isoformat()
    item_id = f"sentinel1-change-{period}"
    return {
        "type": "Feature",
        "stac_version": "1.0.0",
        "id": item_id,
        "bbox": GHANA_BBOX,
        "geometry": {
            "type": "Polygon",
            "coordinates": [[
                [GHANA_BBOX[0], GHANA_BBOX[1]],
                [GHANA_BBOX[2], GHANA_BBOX[1]],
                [GHANA_BBOX[2], GHANA_BBOX[3]],
                [GHANA_BBOX[0], GHANA_BBOX[3]],
                [GHANA_BBOX[0], GHANA_BBOX[1]],
            ]],
        },
        "properties": {
            "datetime": None,
            "start_datetime": f"{period_start.isoformat()}T00:00:00Z",
            "end_datetime": f"{period_end.isoformat()}T23:59:59Z",
            "created": now,
            "forkuor:threshold_db": threshold_db,
            "forkuor:baseline_months": baseline_months,
            "processing:lineage": (
                "Sentinel-1 RTC (MPC) -> linear-to-dB -> trailing baseline mean "
                "-> current period mean -> delta -> joint VV/VH threshold."
            ),
        },
        "assets": {
            "change": {
                "href": cog_url,
                "type": "image/tiff; application=geotiff; profile=cloud-optimized",
                "title": f"Change mask for {period}",
                "roles": ["data"],
            },
        },
        "links": [
            {"rel": "self", "href": _public_url(ITEM_KEY_TEMPLATE.format(period=period))},
            {"rel": "parent", "href": _public_url(CATALOG_KEY)},
            {"rel": "root", "href": _public_url(CATALOG_KEY)},
        ],
    }


def append_item(
    period: str,
    period_start: date,
    period_end: date,
    threshold_db: float,
    baseline_months: int,
    cog_url: str,
) -> str:
    """Fetch or create the catalog, append/replace the period's Item, push back.

    Returns the public URL of the new Item.
    """
    bucket = os.environ.get("R2_BUCKET", "galamsey-static")
    s3 = _client()

    # Cloudflare R2's NoSuchKey error surfaces as botocore.ClientError with
    # an error code, not via boto3's dynamic `s3.exceptions.NoSuchKey` class
    # (which is generated from the AWS S3 service model and only fires for
    # canonical AWS responses). First-ever run = cold bucket = this path.
    try:
        body = s3.get_object(Bucket=bucket, Key=CATALOG_KEY)["Body"].read()
        catalog = json.loads(body)
    except ClientError as e:
        if e.response["Error"]["Code"] == "NoSuchKey":
            catalog = _empty_catalog()
        else:
            raise

    item = _build_item(period, period_start, period_end, threshold_db, baseline_months, cog_url)
    item_key = ITEM_KEY_TEMPLATE.format(period=period)

    # Upload the Item JSON.
    s3.put_object(
        Bucket=bucket,
        Key=item_key,
        Body=json.dumps(item, indent=2).encode(),
        ContentType="application/json",
        CacheControl="public, max-age=300",
    )

    # Add/replace the Item link in the catalog. Catalog links list is the
    # source of truth -- no nested Collection complexity for a single product.
    item_link = {
        "rel": "item",
        "href": _public_url(item_key),
        "type": "application/json",
        "title": item["id"],
    }
    catalog["links"] = [
        link for link in catalog.get("links", [])
        if not (link.get("rel") == "item" and link.get("title") == item["id"])
    ]
    catalog["links"].append(item_link)

    s3.put_object(
        Bucket=bucket,
        Key=CATALOG_KEY,
        Body=json.dumps(catalog, indent=2).encode(),
        ContentType="application/json",
        CacheControl="public, max-age=300",
    )

    log.info(
        "Updated STAC catalog",
        catalog=_public_url(CATALOG_KEY),
        item=_public_url(item_key),
    )
    return _public_url(item_key)
